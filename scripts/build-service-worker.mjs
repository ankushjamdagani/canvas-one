import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

export function normalizeBasePath(value = '') {
  if (!value || value === '/') return '';
  if (!/^\/[a-zA-Z0-9/_-]+$/.test(value)) throw new Error('Canvas base path must be an absolute URL path');
  return value.replace(/\/+$/, '');
}

export function serviceWorkerSource({ basePath = '', assets, version }) {
  const base = normalizeBasePath(basePath);
  const shells = ['/', '/projects', '/brand'].map((route) => `${base}${route}`);
  return `/* Generated by scripts/build-service-worker.mjs. */
const CACHE = ${JSON.stringify(`canvas-one:${base || '/'}:${version}`)};
const PREFIX = ${JSON.stringify(`canvas-one:${base || '/'}:`)};
const BASE = ${JSON.stringify(base)};
const SHELLS = ${JSON.stringify(shells)};
const ASSETS = ${JSON.stringify(assets)};
const ALLOWED = new Set([...SHELLS, ...ASSETS]);
self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // Installation is atomic: an incomplete workspace must not replace a usable worker.
    await cache.addAll([...SHELLS, ...ASSETS]);
  })());
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith(PREFIX) && key !== CACHE) await caches.delete(key);
    }
  })());
});
self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (request.headers.get('RSC') === '1' || url.searchParams.has('_rsc')) return;
  const route = url.pathname.slice(BASE.length);
  const inScope = !BASE || url.pathname === BASE || url.pathname.startsWith(BASE + '/');
  const workspace = route === '/projects' || route === '/project' || route.startsWith('/project/');
  const publicPage = SHELLS.includes(url.pathname) || url.pathname === BASE;
  if (request.mode === 'navigate' && inScope && (workspace || publicPage)) {
    event.respondWith((async () => {
      try { return await fetch(request); }
      catch {
        const cache = await caches.open(CACHE);
        return await cache.match(workspace ? BASE + '/projects' : (url.pathname === BASE ? BASE + '/' : url.pathname))
          || Response.error();
      }
    })());
    return;
  }
  if (!ALLOWED.has(url.pathname) || !ASSETS.includes(url.pathname) || url.search) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    return await cache.match(url.pathname) || fetch(request);
  })());
});
`;
}

async function listFiles(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const groups = await Promise.all(entries.map((entry) => entry.isDirectory()
    ? listFiles(path.join(directory, entry.name), `${prefix}${entry.name}/`)
    : [`${prefix}${entry.name}`]));
  return groups.flat();
}

export async function buildServiceWorker(root = process.cwd(), basePath = process.env.NEXT_PUBLIC_CANVAS_BASE_PATH || '') {
  const base = normalizeBasePath(basePath);
  const buildId = (await readFile(path.join(root, '.next/BUILD_ID'), 'utf8')).trim();
  // Walking the full static output includes chunks loaded only after entering a canvas,
  // worker bundles, local fonts and CSS; initial-route manifests alone omit lazy assets.
  const staticFiles = (await listFiles(path.join(root, '.next/static'))).filter((file) => !file.endsWith('.map')).sort();
  const pwaFiles = (await listFiles(path.join(root, 'public/pwa'))).sort();
  const assets = [...staticFiles.map((file) => `${base}/_next/static/${file}`),
    ...pwaFiles.map((file) => `${base}/pwa/${file}`), `${base}/favicon.svg`];
  const version = createHash('sha256').update(buildId + JSON.stringify(assets)).digest('hex').slice(0, 20);
  await writeFile(path.join(root, 'public/sw.js'), serviceWorkerSource({ basePath: base, assets, version }));
  return { version, assetCount: assets.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const result = await buildServiceWorker(path.resolve(process.argv[2] || 'apps/web'));
  console.log(`Canvas One offline worker generated: ${result.assetCount} assets (${result.version})`);
}
