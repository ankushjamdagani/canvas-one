import { expect, it } from "vitest";
import { newProject, validateGraph, clone } from "./model";
import { balancedLookup, serviceInstances } from "./routing";
import { useEditor } from "../state/editor";
import { Simulation } from "../simulation/engine";
import { createSavedRun, modelChanges, validateSavedRun, comparisonStatus } from "./results";
import { exportProject, importProject } from "../persistence/projects";
it("replicas, cache and checkpoints are atomic graph edits and restore across scenarios", () => {
  const p = newProject(); p.graph = balancedLookup(1); useEditor.getState().load(p);
  const before = clone(p.graph);
  useEditor.getState().addServiceInstance();
  const scaled = clone(useEditor.getState().project.graph);
  expect(validateGraph(scaled)).toEqual([]);
  expect(modelChanges(before, scaled).join()).toContain("Service instance 2 added");
  useEditor.getState().undo(); expect(useEditor.getState().project.graph).toEqual(before);
  useEditor.getState().redo(); useEditor.getState().insertCache();
  expect(validateGraph(useEditor.getState().project.graph)).toEqual([]);
  useEditor.getState().checkpoint("Balanced cache");
  const checkpoint = useEditor.getState().project.checkpoints.at(-1)!;
  useEditor.getState().useScenario("jobs"); useEditor.getState().restore(checkpoint.id);
  expect(useEditor.getState().project.graph).toEqual(checkpoint.graph);
  expect(validateGraph(useEditor.getState().project.graph)).toEqual([]);
});
it("saved per-instance results roundtrip with exact graph identity and reject corrupted routing", () => {
  const p = newProject(); p.graph = balancedLookup();
  const run = createSavedRun({ id: "routing-run", graph: p.graph, metrics: new Simulation(p.graph).advance(30) }, "Two replicas");
  p.savedRuns = [run]; p.expandedNodeIds = [p.graph.nodes.find((n) => n.kind === "balancer")!.id];
  p.subsystems = [{id: "pool", name: "Services", nodeIds: serviceInstances(p.graph).map((n) => n.id), collapsed: true}];
  const imported = importProject(exportProject(p));
  expect(imported.graph).toEqual(p.graph); expect(imported.savedRuns![0].metrics).toEqual(run.metrics);
  expect(imported.subsystems).toEqual(p.subsystems); expect(imported.expandedNodeIds).toEqual(p.expandedNodeIds);
  const bad = clone(run); bad.metrics.nodes[serviceInstances(p.graph)[0].id].arrived++;
  expect(validateSavedRun(bad).join()).toContain("routing counts");
  useEditor.getState().load(p); useEditor.getState().useScenario("jobs"); useEditor.getState().restoreRun(run.id);
  expect(useEditor.getState().project.graph).toEqual(run.graph);
  const scaled = clone(p.graph); serviceInstances(scaled)[1].workers = 3;
  expect(modelChanges(p.graph, scaled).join()).toContain("Service instance 2 workers: 1 → 3");
  const next = createSavedRun({id: "next", graph: scaled, metrics: new Simulation(scaled).advance(30)}, "More workers");
  expect(comparisonStatus(run, next).matched).toBe(true);
});
