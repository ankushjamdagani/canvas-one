export type ThemeMode = 'light' | 'dark';

export interface ThemeTokens {
  // Surface hierarchy
  desk: string;
  shell: string;
  canvas: string;
  panel: string;
  sunken: string;
  raised: string;
  // Text hierarchy
  ink: string;
  body: string;
  muted: string;
  faint: string;
  // Border/line hierarchy
  l1: string;
  l2: string;
  l3: string;
  l4: string;
  dot: string;
  // Semantic: branch
  branch: string;
  bTint: string;
  bEdge: string;
  // Semantic: risk/error
  risk: string;
  rTint: string;
  rEdge: string;
  // Primary action
  action: string;
  onAction: string;
  aTint: string;
  aEdge: string;
  ring: string;
  mark: string;
  aText: string;
  // Notes/sticky
  sticky: string;
  stickyInk: string;
  // Shadow base (RGB triplet string, e.g. "22,32,29")
  sh: string;
  // Shadow alpha multiplier (dark themes use higher values)
  shA: number;
  // Whether this combo is a dark-mode palette
  isDark: boolean;
}

